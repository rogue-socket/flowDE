export const FLOWDE_PYTHON_TRACER = [
  'import json',
  'import os',
  'import runpy',
  'import sys',
  'import time',
  'import traceback',
  '',
  "TRACE_PREFIX = 'FLOWDE_TRACE:'",
  '',
  'def emit(payload):',
  '    try:',
  '        serialized = json.dumps(payload, ensure_ascii=False)',
  '    except Exception as serialization_error:',
  "        serialized = json.dumps({'event': 'trace_error', 'message': f'serialization failure: {serialization_error}'})",
  '    sys.stderr.write(f"{TRACE_PREFIX}{serialized}\\n")',
  '    sys.stderr.flush()',
  '',
  'def safe_value(value):',
  '    try:',
  '        json.dumps(value)',
  '        return value',
  '    except Exception:',
  '        return repr(value)',
  '',
  'def snapshot_locals(values):',
  '    snapshot = {}',
  '    for key, value in values.items():',
  "        if key.startswith('__'):",
  '            continue',
  '        snapshot[key] = safe_value(value)',
  '    return snapshot',
  '',
  'def snapshot_inputs(frame):',
  '    arg_count = frame.f_code.co_argcount + frame.f_code.co_kwonlyargcount',
  '    names = list(frame.f_code.co_varnames[:arg_count])',
  '    captured = {}',
  '    for name in names:',
  '        if name in frame.f_locals:',
  '            captured[name] = safe_value(frame.f_locals[name])',
  '    return captured',
  '',
  'def make_tracer(workspace_root):',
  '    workspace_root = os.path.abspath(workspace_root)',
  '    tracer_file = os.path.abspath(__file__)',
  '',
  '    def tracer(frame, event, arg):',
  '        filename = os.path.abspath(frame.f_code.co_filename)',
  '        if filename == tracer_file:',
  '            return tracer',
  '        if not filename.startswith(workspace_root):',
  '            return tracer',
  '',
  '        payload = {',
  "            'event': event,",
  "            'timestamp': time.time(),",
  "            'file': filename,",
  "            'line': frame.f_lineno,",
  "            'def_line': frame.f_code.co_firstlineno,",
  "            'function': frame.f_code.co_name,",
  "            'qualname': getattr(frame.f_code, 'co_qualname', frame.f_code.co_name),",
  "            'locals': snapshot_locals(frame.f_locals)",
  '        }',
  '',
  "        if event == 'call':",
  "            payload['inputs'] = snapshot_inputs(frame)",
  "        elif event == 'return':",
  "            payload['output'] = safe_value(arg)",
  "        elif event == 'exception':",
  '            exc_type, exc_value, _ = arg',
  "            exc_name = getattr(exc_type, '__name__', str(exc_type))",
  "            payload['exception'] = f'{exc_name}: {exc_value}'",
  '',
  '        emit(payload)',
  '        return tracer',
  '',
  '    return tracer',
  '',
  'def main():',
  '    if len(sys.argv) < 3:',
  "        emit({'event': 'trace_error', 'message': 'Usage: tracer.py <entry_path> <workspace_root> [args...]'})",
  '        return 2',
  '',
  '    entry_path = os.path.abspath(sys.argv[1])',
  '    workspace_root = os.path.abspath(sys.argv[2])',
  '',
  '    if not os.path.exists(entry_path):',
  "        emit({'event': 'trace_error', 'message': f'Entry file not found: {entry_path}'})",
  '        return 2',
  '',
  '    old_argv = sys.argv[:]',
  '    sys.argv = [entry_path] + sys.argv[3:]',
  '',
  '    tracer = make_tracer(workspace_root)',
  '    sys.settrace(tracer)',
  '',
  '    try:',
  "        runpy.run_path(entry_path, run_name='__main__')",
  "        emit({'event': 'trace_complete', 'timestamp': time.time()})",
  '        return 0',
  '    except SystemExit as exit_exc:',
  "        code = exit_exc.code if isinstance(exit_exc.code, int) else 0",
  "        emit({'event': 'trace_complete', 'timestamp': time.time(), 'exit_code': code})",
  '        return code',
  '    except Exception as runtime_error:',
  '        emit({',
  "            'event': 'trace_error',",
  "            'timestamp': time.time(),",
  "            'message': repr(runtime_error),",
  "            'traceback': traceback.format_exc()",
  '        })',
  '        return 1',
  '    finally:',
  '        sys.settrace(None)',
  '        sys.argv = old_argv',
  '',
  "if __name__ == '__main__':",
  '    raise SystemExit(main())',
  ''
].join('\n');
